-- 동화 이어서 틀기(연속 보기) — 켜고 끈 것을 계정에 남긴다.
-- ─────────────────────────────────────────────────────────────
-- 사용법: Supabase → SQL Editor 에 붙여넣고 Run. (한 번만)
--
-- 왜 필요한가:
--   지금은 이 설정이 브라우저(localStorage)에만 있다. 같은 기기에서는 아이디별로
--   나뉘어 잘 지켜지지만, 휴대폰으로 갈아타거나 앱을 지웠다 깔면 사라진다.
--   잠자리에 틀어 두려고 켜 둔 설정이 기기를 바꿀 때마다 꺼져 있으면
--   "왜 또 안 넘어가지" 를 매번 다시 겪는다.
--
-- 왜 새 테이블이 아니라 profiles 의 컬럼인가:
--   계정에 하나만 붙는 참/거짓 값이다. 아이 정보(child)도 같은 자리에 두었고,
--   한 번 읽을 때 같이 딸려 와서 왕복이 늘지 않는다.
--
-- 이 SQL 을 돌리지 않아도 앱은 그대로 돈다 — 컬럼이 없으면 저장이 조용히 무시되고
-- 기기 안 설정으로만 동작한다(child 컬럼과 같은 규칙).

alter table public.profiles
  add column if not exists auto_next boolean not null default false;

comment on column public.profiles.auto_next is
  '동화 이어서 틀기 — 한 편이 끝나면 묻지 않고 같은 책장의 다음 동화를 바로 읽어 준다';

-- 읽기·쓰기 권한은 profiles 에 이미 걸린 정책을 그대로 쓴다(본인 행만).
-- 따로 정책을 더하지 않는다 — 더하면 기존 정책과 어느 쪽이 이기는지 헷갈린다.
