/**
 * "누구랑" 한 줄을 만든다.
 *
 * 핵심: 이름을 넣었으면 그 이름을 그대로 등장인물 이름으로 쓰고, 안 넣었으면
 * 이름을 **지어내지 말고** 칩 그대로("친구", "동생")로만 부른다. 안 그러면
 * "친구 토토와..."처럼 칩 라벨에 지어낸 이름이 엉겨붙는다.
 *
 * 성별도 같이 못박는다. 안 주면 모델이 이름으로 짐작해 남자 친구가 여자아이로
 * 나오는 사고가 난다 — 실제 친구가 주인공 옆에 서는 책이라 이게 바로 티가 난다.
 */
/**
 * 어른 동행 — 성별을 '여자아이'로 붙이면 안 되는 사람들.
 *
 * '선생님이랑'을 고르고 성별을 '여자'로 두면 프롬프트가 "여자아이다"라고 못박아
 * 선생님이 어린이로 그려졌다(실제로 났다). 어른은 어른이라고 말해 줘야 한다.
 */
const ADULT_COMPANIONS = new Set([
  "선생님", "엄마", "아빠", "할머니", "할아버지", "이모", "삼촌", "고모", "외삼촌", "큰아빠", "작은아빠",
]);

function whoLine(
  label: string,
  who: string,
  whoName: string,
  whoGender = "",
  friends: { name: string; gender: string }[] = [],
): string {
  /*
   * 예전엔 여기서 `if (!who) return ""` 로 끝냈다. 그래서 '직접 이야기 구성'처럼
   * 동행 칩(who)을 쓰지 않는 갈래에서는 부모가 적어 준 **친구 이름과 성별이 모델에
   * 한 줄도 닿지 않았다**. 칩이 없어도 이름·성별·친구 목록 중 하나라도 있으면 알려 준다.
   */
  if (!who && friends.length === 0 && !whoName && !whoGender) return "";
  // "친구랑"→"친구", "동생이랑"→"동생", "선생님이랑"→"선생님". 조사만 떼어 지칭어로.
  const term = who ? who.replace(/(이랑|랑|이와|와|과|하고)$/u, "") : "";
  const isAdult = ADULT_COMPANIONS.has(term);
  // "여자"/"남자" → 이야기와 삽화 양쪽에서 흔들리지 않게 한 문장으로 붙인다.
  // 어른에게 '아이'를 붙이면 그림에서 어린이로 그려지므로 말을 갈라 쓴다.
  const g = whoGender
    ? isAdult
      ? ` ${whoGender} 어른이다 — 아이가 아니라 어른으로, 이야기 내내 그리고 그림에서도 ${whoGender} 어른으로 그린다.`
      : ` ${whoGender}아이다 — 이야기 내내, 그리고 그림에서도 ${whoGender}아이로 그린다. 이름으로 성별을 짐작하지 않는다.`
    : isAdult
      ? " 어른이다 — 아이가 아니라 어른으로 그린다."
      : "";

  /*
   * 친구가 여럿인 경우. 한 명씩 이름·성별을 못박아야 인물이 뭉개지지 않는다.
   * 여럿이 나오면 그림에서 서로 닮게 그려지는 사고가 특히 잘 나므로, 생김새를
   * 서로 다르게 정하라는 말을 여기서 한 번 더 건다.
   */
  if (friends.length > 0) {
    const list = friends
      .map((f, i) => {
        const name = f.name || `친구${i + 1}`;
        const sex = f.gender ? `${f.gender}아이` : "성별은 이야기에 맞게";
        return `${name}(${sex})`;
      })
      .join(", ");
    return [
      `${label}: 친구 ${friends.length}명 — ${list}.`,
      `  적어 준 이름과 성별을 그대로 쓴다. 이름을 바꾸거나 친구를 더 만들지 않는다.`,
      `  친구들끼리도 서로 확실히 달라 보이게 정한다 — 머리 모양·머리 색·옷 색을 각자 다르게.`,
      `  주인공까지 ${friends.length + 1}명이라 한 장면에 다 넣으면 복잡해진다. 쪽마다 꼭 필요한 인물만 등장시킨다.`,
    ].join("\n");
  }

  /*
   * 이름을 적었으면 **역할과 이름을 함께** 준다.
   * 예전엔 이름만 줘서 '선생님이랑 + 김밥샘'이 그냥 "김밥샘"이 되고, 선생님이라는
   * 역할이 사라져 또래 아이로 그려졌다.
   */
  if (whoName) {
    return term
      ? `${label}: ${term} — 이름은 "${whoName}"이다 (실제 이름이니 그대로 쓰고 바꾸지 않는다. ${term}라는 역할도 유지한다.${g})`
      : `${label}: ${whoName} (실제 이름이다 — 이 이름을 그대로 등장인물 이름으로 쓴다.${g})`;
  }
  if (!term) {
    // 칩도 이름도 없는데 성별만 있는 경우(직접 구성) — 성별만이라도 알려 준다.
    return `${label}: 함께 나오는 사람은${g}`;
  }
  return `${label}: ${term} (이름을 지어내지 말고 '${term}'라고만 부른다.${g})`;
}

function materialLines(m: StoryMaterial): string[] {
  if (m.kind === "direct") {
    /*
     * 함께 나오는 인물은 여기서도 알려 준다.
     *
     * 원고에 이름은 적혀 있으니 누가 나오는지는 알아낸다. 그런데 **성별은 이름만으로
     * 알 수 없다** — 예전에 남자 친구가 여자로 그려진 그 문제다. 다른 갈래에는
     * 이 줄이 있는데 직접 구성에만 빠져 있어서, 부모가 성별을 골라도 닿지 않았다.
     */
    const who = whoLine("- 함께 나오는 이", m.who, m.whoName, m.whoGender, m.friends);
    return m.directMode === "full"
      ? [
          "아래는 부모가 직접 완성한 동화 원고다. 사건·인물·대사·결말을 새로 만들거나 삭제하지 않는다.",
          "맞춤법과 어색한 조사만 바로잡고, 아이 연령에 맞게 문장을 다듬어 선택한 장면 수로 나눈다.",
          "원문에 없는 교훈, 악역, 반전, 새 인물을 추가하지 않는다.",
          who,
          `- 부모의 완성 원고:\n${m.directText}`,
        ]
      : [
          "아래 기승전결은 부모가 직접 정한 이야기다. 네 부분의 사실과 순서와 결말을 반드시 보존한다.",
          "빈 곳을 임의의 큰 사건으로 채우지 말고, 연결 문장과 자연스러운 대사만 보완한다.",
          who,
          `- 기(시작): ${m.directOpening}`,
          `- 승(전개): ${m.directDevelopment}`,
          `- 전(위기): ${m.directCrisis}`,
          `- 결(결말): ${m.directEnding}`,
        ];
  }
  if (m.kind === "today") {
    return [
      "아래는 아이가 오늘 실제로 겪은 일이다. 이 경험을 살려 따뜻한 동화로 각색한다.",
      "완전히 다른 이야기로 바꾸지 말고, 실제 있었던 일의 결을 지키되 아이가 주인공으로",
      "빛나게 하고, 속상한 일이면 마지막엔 마음이 풀리게 한다.",
      m.place ? `- 어디에서: ${m.place}` : "",
      m.place
        ? `- 장소 연속성: '${m.place}'를 이 이야기의 기본 장소로 고정한다. 사용자가 적은 사건에 실제 이동이 없는 한 다른 집·한옥·공원·유치원 같은 장소를 새로 만들지 않는다.`
        : "- 장소 연속성: 사용자가 말하지 않은 새 장소를 임의로 추가하지 않는다.",
      whoLine("- 누구랑", m.who, m.whoName, m.whoGender, m.friends),
      m.happening ? `- 무슨 일이 있었나: ${m.happening}` : "",
      m.feeling ? `- 그때 아이 기분: ${m.feeling}` : "",
      m.ending
        ? `- 실제 결말(반드시 지킬 사실): "${m.ending}". 이 일은 이야기 안에서 실제로 일어나야 한다 — 지우거나 다른 결말로 미화하면 안 된다. 그 사실을 담은 뒤에, 마지막 쪽에서 아이가 배우거나 마음이 다독여지게 마무리한다.`
        : "",
    ];
  }
  if (m.kind === "emotion") {
    return [
      m.emotion
        ? `아이가 '${m.emotion}' 마음을 느꼈다. 이 감정을 다루는 감정동화를 짓는다.`
        : "아이의 마음을 다루는 감정동화를 짓는다.",
      m.emotion === "좋아해요"
        ? "'좋아해요'는 연애 감정으로 단정하지 말고, 입력된 상황에 맞춰 가족 사랑·우정·동물이나 대상에 대한 애정과 고마움으로 따뜻하게 표현한다. 좋아하는 마음을 말과 행동으로 건강하게 전하되 상대의 마음과 경계도 존중한다."
        : "",
      "감정에 이름을 붙여 주고, 몸으로 느끼는 감각(가슴이 콩닥콩닥, 얼굴이 뜨끈 등)으로",
      "표현하며, 아이가 스스로 감정을 알아차리고 다독이는 과정을 이야기로 만든다.",
      "감정 자체를 나쁘다고 하지 않는다.",
      m.situation ? `- 그런 마음이 든 때: ${m.situation}` : "",
      whoLine("- 누구랑", m.who, m.whoName, m.whoGender, m.friends),
      m.ending
        ? `- 어떻게 끝나면 좋을지(부모가 정함): "${m.ending}". 이 결을 마지막 쪽이 반드시 담는다. 다만 그 말을 그대로 옮겨 적지 말고, 눈에 보이는 장면과 아이의 대사로 그려 낸다.`
        : "",
    ];
  }
  return [
    "아래 재료를 모두 살려서 상상 이야기를 짓는다:",
    m.subject ? `- 이야기 소재: ${m.subject}` : "",
    whoLine("- 함께하는 이", m.who, m.whoName, m.whoGender, m.friends),
    m.happening ? `- 중심 사건: ${m.happening}` : "",
    m.extra ? `- 아이가 더 넣고 싶은 이야기: ${m.extra}` : "",
    m.ending
      ? `- 어떻게 끝나면 좋을지(부모가 정함): "${m.ending}". 이 결을 마지막 쪽이 반드시 담는다. 다만 그 말을 그대로 옮겨 적지 말고, 눈에 보이는 장면과 아이의 대사로 그려 낸다.`
      : "",
  ];
}

/**
 * 이름 가드 — 생성 결과에 주인공 이름이 정확히 들어있는지. 모델이 흔한 이름으로
 * 바꿔치기하는 사고(하온→하윤)를 프롬프트로 막아도 확률적으로 재발할 수 있어,
 * 서버가 최종 검사하고 틀리면 한 번 다시 짓는다. (아이 이름은 이 앱의 핵심 가치)
 */
function nameOk(name: string, text: string): boolean {
  return text.includes(name);
}

/**
 * 한글을 '완성형(NFC)'으로 맞춘다 — 만들어진 글이 책에 들어가기 전에 한 번.
 *
 * 같은 '얘'라도 한 글자로 온 것(U+C598)과 ㅇ+ㅒ로 쪼개져 온 것(U+110B U+1164)이 있는데,
 * 동화책 글꼴에는 쪼개진 자모가 없어서 그 글자만 ◆? 로 나온다(실제 발생).
 * 낭독 색칠도 '몇 번째 글자까지'로 도는 터라, 쪼개진 글자는 둘로 세어져 색칠이 밀린다.
 */
function nfc(t: string): string {
  return typeof t === "string" ? t.normalize("NFC") : t;
}

/**
 * '이름' 칸에 들어와도 이름이 아닌 말들. 부모가 "누구랑"의 이름 칸에 "동생"처럼
 * 적는 일이 있어서, 조사 교정이 이런 낱말을 망가뜨리지 않도록 막아 둔다.
 */
const COMMON_NOUNS = new Set([
  "동생", "형", "누나", "언니", "오빠", "친구", "엄마", "아빠",
  "할머니", "할아버지", "선생님", "이모", "삼촌", "고모", "사촌",
]);

/**
 * 이름 뒤 조사 교정 — 프롬프트로 막아도 확률적으로 새는 것을 마지막에 손본다.
 *
 * 받침 있는 이름은 '이'를 붙인 "하온이"가 기본형인데, 모델이 종종 이걸 빠뜨려
 * "하온은 웃었어요"(딱딱함)나 "하온가 달렸어요"(비문)를 낸다. 부모가 읽어 주는
 * 글이라 이런 문장 하나가 바로 티가 나서, 명백히 틀린 형태만 골라 고친다.
 *
 * 손대지 않는 것: "하온이 열쇠를 …". 주어일 수도("하온이가"의 누락) 소유일 수도
 * ("하온이의 열쇠") 있어 기계가 판단할 수 없다. 그건 프롬프트에 맡긴다.
 */
export function fixNameJosa(name: string, text: string): string {
  const trimmed = name.trim();
  if (!trimmed || !text) return text;
  // 보통명사에는 이 규칙이 통하지 않는다 — "동생은 웃었어요"는 맞는 말인데
  // "동생이는"으로 바꿔버리면 오히려 틀린다. 사람 이름일 때만 손댄다.
  if (COMMON_NOUNS.has(trimmed)) return text;
  const last = trimmed.slice(-1);
  const code = last.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return text; // 한글 이름만
  if ((code - 0xac00) % 28 === 0) return text; // 받침 없는 이름은 '이'를 붙이지 않는다

  const esc = trimmed.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  // 조사 뒤에 한글이 이어지면 다른 낱말일 수 있으니 건드리지 않는다.
  const rules: [RegExp, string][] = [
    [new RegExp(`${esc}은(?![가-힣])`, "g"), `${trimmed}이는`], // 딱딱함
    [new RegExp(`${esc}는(?![가-힣])`, "g"), `${trimmed}이는`], // 비문
    [new RegExp(`${esc}가(?![가-힣])`, "g"), `${trimmed}이가`], // 비문
    [new RegExp(`${esc}를(?![가-힣])`, "g"), `${trimmed}이를`], // 비문
    [new RegExp(`${esc}야(?![가-힣])`, "g"), `${trimmed}아`], // 부를 때
  ];
  return rules.reduce((out, [re, to]) => out.replace(re, to), text);
}

export async function generateOutline(input: {
  child: ChildProfile;
  material: StoryMaterial;
  /** 장면(쪽) 수 3~8. 없으면 기본 8장면. 줄거리를 이 개수만큼 장면으로 나눈다. */
  pageCount?: number;
  /** 특별한 날(생일·돌·졸업·동생). 있으면 그 날을 축하하는 이야기가 된다. */
  occasion?: string;
  /** 분위기(무드). 이야기 톤에 반영한다. */
  mood?: string;
}): Promise<ParsedOutline> {
  // 넘어온 쪽수를 3~8로 가둔다 — 클라이언트 값은 믿지 않는다.
  const pageCount = clampPageCount(input.pageCount);

  /*
   * 이야기 뼈대를 한 장 고른다. 갈래마다 어울리는 골격이 다르고(감정동화는 굴곡이,
   * 상상은 모험의 곡선이 필요하다), 매번 무작위로 골라 한 집에서 여러 편을 만들어도
   * 구조가 겹치지 않게 한다. 「직접 이야기 구성」은 부모가 짠 흐름이 있어 씌우지 않는다.
   * 뼈대를 못 고르면(카드 없음) 그냥 빈 줄이라 기존 동작 그대로다.
   */
  const template = pickBeatTemplate(input.material.kind, pageCount, input.child.age);
  const beatLines = template ? beatPlanLines(template, pageCount) : [];

  // 이름 가드 — 최대 2회. 1회차에 이름이 틀리면 경고를 덧붙여 한 번만 다시 짓는다.
  let outline: ParsedOutline | null = null;
  for (let attempt = 1; attempt <= 2; attempt++) {
    const message = await client.messages.create({
      model: MODEL,
      max_tokens: 2000,
      system: OUTLINE_SYSTEM,
      thinking: { type: "adaptive" },
      output_config: { effort: "medium" },
      messages: [
        {
          role: "user",
          content: [
            `아이: ${describeChild(input.child)}`,
            // 뼈대를 고른 경우 쪽 배분은 뼈대가 이미 정해 놨다. 여기서 기승전결 배분을
            // 또 일러 주면 장면 계획이 둘이 되어 서로 자리를 다툰다(뼈대는 3장면을
            // '터뜨림'이라 하고 pageGuide는 같은 자리를 '승'이라 하는 식). 하나만 준다.
            template
              ? `장면 수: ${pageCount}장면 — 아래 뼈대가 정한 장면 순서를 그대로 따른다.`
              : `장면 수: ${pageCount}장면 — ${pageGuide(pageCount)}`,
            ...materialLines(input.material),
            // 뼈대 카드 — 좋은 그림책이 쓰는 골격을 장면별로 배분해 준다.
            // 재료 뒤에 놓는 이유: 뼈대가 재료를 이기면 안 되고, 재료를 뼈대에 담아야 한다.
            ...beatLines,
            input.occasion
              ? `특별한 날: ${input.occasion} — 이 날을 축하하는 이야기로 지어라. 축하가 결말에 자연스럽게 스며들게 한다.`
              : "",
            input.mood ? `분위기: ${input.mood} — 이야기 전체 톤에 반영한다.` : "",
            attempt > 1
              ? `경고: 직전 생성에서 주인공 이름 표기가 틀렸다. 이름은 "${input.child.name}"이다 — 비슷한 다른 이름 절대 금지. (조사는 자연스럽게: ${josaGuide(input.child.name)})`
              : "",
          ]
            .filter(Boolean)
            .join("\n"),
        },
      ],
    });

    outline = parseOutline(textOf(message));

    if (outline.scenes.length !== pageCount) {
      throw new Error(
        `${pageCount}장면이어야 하는데 ${outline.scenes.length}장면이 나왔습니다.`,
      );
    }

    const joined = outline.title + " " + outline.scenes.map((s) => s.text).join(" ");
    if (nameOk(input.child.name, joined)) break;
    if (attempt === 2) {
      // 두 번 다 틀리면 그대로 내보내되 로그를 남긴다 — 부모가 줄거리에서 보고 다시 지을 수 있다.
      console.warn(`[outline] 이름 불일치 2회: "${input.child.name}"`);
    }
  }

  // 부모가 줄거리를 먼저 보고 고르므로, 여기서부터 조사가 맞아야 한다.
  const names = [input.child.name, input.material.whoName].filter(Boolean);
  const fix = (t: string) => names.reduce((s, n) => fixNameJosa(n, s), nfc(t));
  return {
    ...outline!,
    title: fix(outline!.title),
    scenes: outline!.scenes.map((s) => ({ ...s, text: fix(s.text) })),
  };
}

const STORY_SYSTEM = `${VOICE}
독자가 아이인 만큼 노골적인 폭력·공포·성인 소재를 쓰지 않는다. 갈등은 안전하게 해소하고 아이를 탓하거나 겁주지 않는다.
공통 작품 테마는 '아이의 실제 마음에서 시작해 작은 모험을 스스로 선택하고, 따뜻하고 안전하게 돌아오는 성장 이야기'다. 사용자가 고른 공룡·우주·습관 같은 소재는 유지하되 훈계보다 아이의 선택과 감정 회복을 보여 준다.

확정된 줄거리는 장면별로 나뉘어 있다. **1장면 → 1쪽**으로, 장면 하나를 한 쪽 본문으로
옮긴다. 이야기를 새로 짓거나 장면을 합치거나 나누지 말고, 장면 개수 그대로 쪽을 낸다
(@@PAGE@@ 번호가 장면 번호와 일치해야 한다). 각 장면의 줄거리에 살을 붙여 본문으로만
만든다.

@@TEXT@@에 쓰는 것이 **아이가 실제로 보게 될 동화책 한 쪽의 글**이다. 부모가 그 자리에서
소리 내어 읽어 준다. 쓰고 나면 반드시 소리 내어 읽어 보듯 확인한다 — 읽다가 걸리는 곳,
숨이 안 쉬어지는 긴 문장, 조사가 어색한 곳이 있으면 고쳐서 낸다.
특히 이름 뒤 조사를 매 쪽 확인한다: 주어 자리는 "하온이는/하온이가"이지 "하온은"이나
"하온이"가 아니다. 이 실수가 가장 자주 나오니 쪽마다 눈으로 짚는다.

@@CHARACTER@@에는 이야기에 나오는 인물을 **한 명씩 한 줄로** 적는다(\`이름 | 생김새\`).
주인공뿐 아니라 **여러 쪽에 나오는 친구·형제·어른도 빠짐없이** 적는다 — 여기 없는 인물은
쪽마다 다른 얼굴로 그려진다.
생김새는 그리는 사람이 보고 바로 그릴 수 있게 구체적으로 쓴다: 머리 모양과 머리 색,
입은 옷과 그 색, 늘 몸에 붙어 있는 것(안경·머리핀·모자) 순으로.

**옷은 '늘 입는 옷'을 적는다. 한 장면에만 맞는 옷은 적지 않는다.**
잠옷·수영복·우비·한복·잠바만 걸친 모습처럼 **그 쪽에서만 입는 옷**을 여기 적으면,
그 옷이 1쪽부터 마지막 쪽까지 따라다닌다. 실제로 잠에서 깨는 장면으로 시작한
동화에서 아이가 **잠옷에 맨발로 눈밭에 서 있었다.**
여기에는 티셔츠·바지·원피스처럼 평소 옷을 적고, 잠옷이나 겉옷은 그 쪽 @@IMG@@에만 적는다.

옷은 그 쪽의 장소와 날씨에 맞아야 한다. 밖으로 나가는 쪽에서는 신발을 신고,
추운 날이면 겉옷을 입는다. 자는 쪽에서만 잠옷이다. 이건 @@IMG@@에 적는다 —
예: \`하온이는 패딩을 입고 목도리를 두르고 장갑을 꼈다.\`

**이야기 중간에 생기거나 사라지는 물건은 절대 여기 적지 않는다.**
장화·우산·아이스크림·풍선·선물·가방처럼 어느 쪽에서 받거나 신거나 들게 되는 것은
생김새가 아니라 그 쪽의 사건이다. 여기 적으면 그 물건이 **1쪽부터 마지막 쪽까지
붙어 다닌다** — 엄마가 장화를 꺼내 주는 쪽에서 아이가 이미 그 장화를 신고 있고,
장화가 두 켤레 그려진다(실제로 난 사고다).
그런 물건은 @@IMG@@의 \`물건:\` 줄에만 적는다. 거기 적으면 그 쪽에만 나온다.

여기 적을 것은 **이야기가 끝날 때까지 변하지 않는 것**뿐이다 — 머리, 얼굴, 늘 입는 옷, 신발.

여기서 가장 중요한 것은 **인물끼리 확실히 달라 보이게** 쓰는 것이다.
주인공과 친구가 둘 다 "까만 머리에 파란 옷"이면 그림에서 누가 누군지 구별되지 않고,
결국 **같은 아이가 두 명 그려진다**(실제로 자주 나는 사고다).
그러니 친구·형제는 주인공과 다음 둘을 **반드시 다르게** 정한다:
  ① 머리 **모양과 길이** — 짧은 머리 / 단발 / 양갈래 / 곱슬 / 스포츠머리처럼 한눈에 다르게
  ② 옷 색 — 주인공이 파란 옷이면 친구는 노랑·초록처럼 한눈에 다른 색으로
키나 체격, 늘 지니는 물건까지 다르면 더 좋다. 주인공의 특징을 친구에게 그대로
옮겨 적지 않는다.

**머리 색으로 구별하지 않는다.** 한국 아이들이다. 머리 색은 모두 검정이나 짙은
갈색이고, 그 안에서 조금 다를 뿐이다. 금발·노란 머리·빨간 머리·은발은 절대 쓰지
않는다 — 실제로 "노란빛 스포츠머리"라고 적었더니 한국 아이 넷 중 하나만 금발
서양 아이로 그려졌다. 구별은 **머리 모양과 옷 색**으로 한다.

**어른(엄마·아빠·할머니·할아버지·이모·삼촌·선생님)의 얼굴 특징을 지어내지 않는다.**
이 동화의 어른은 **아이의 실제 가족**이다. 그래서 있고 없음이 한눈에 갈리는 것 —
**안경·수염·모자·귀걸이·점·문신** — 은 부모가 알려 준 게 아니면 **절대 적지 않는다.**
실제로 "짧은 머리에 검은 뿔테 안경"이라고 적었더니, 안경을 안 쓰는 아빠가 6쪽 내내
안경잡이로 그려졌다. 아이가 "우리 아빠"로 못 알아보면 이 책은 실패한 것이다.
어른을 서로 구별하는 데는 **머리 길이·묶음(단발/긴 머리/하나로 묶음/짧은 머리)과
옷 색** 두 가지면 충분하다. 그것만 적는다.
예: 엄마 | 어깨까지 오는 검은 머리, 연분홍 니트와 청바지.
예: 아빠 | 짧은 검은 머리, 회색 후드티와 검은 바지.

**남자아이에게 단발·긴 머리를 주지 않는다.** 성별이 주어졌으면 그대로 지킨다 —
남자아이는 짧은 머리·스포츠머리·약간 긴 앞머리, 여자아이는 단발·긴 머리·양갈래·
묶은 머리처럼 한눈에 알아볼 수 있게 적는다. 실제로 남자 친구에게 "검은 단발머리"를
적었더니 그림에서 여자아이로 그려졌다. 이름으로 성별을 짐작하지 말고, 위에 주어진
성별을 그대로 따른다.

@@IMG@@에는 그 쪽의 **장면만** 적는다. 그림체나 카메라 용어는 적지 않는다.
반드시 첫 문장을 \`등장인물 N명: 이름1, 이름2.\` 형식으로 시작한다. 사람이 없는
풍경이면 \`등장인물 0명.\`이라고 쓴다. 그 쪽에 실제로 보이는 인물의 **고유 이름을
모두** 적고, 나오지 않는 인물은 절대 적지 않는다. "친구들", "아이들"처럼 누구인지
모르는 뭉뚱그린 말도 쓰지 않는다.

적은 숫자가 곧 **그림에 보일 사람 수**다. 이름 없는 배경 아이·지나가는 사람·다른
반 아이를 그리면 안 되므로, @@IMG@@에 그런 사람을 암시하는 말(교실이 북적인다,
아이들이 모여 있다, 다른 친구들 사이에서)도 쓰지 않는다. 실제로 "등장인물 3명"인
쪽에 모르는 아이 넷이 배경에 더 그려졌고, 다음 쪽에서 사라져 얼굴이 바뀐 것처럼
보였다.
그 다음에는 이름마다 위치와 행동을 하나씩 분명히 배정한다. 예:
\`민준은 다리 왼쪽 입구에서 발을 멈추고 난간을 잡는다. 서연은 다리 가운데에서
민준을 돌아본다.\` 누가 앞/뒤인지, 어느 쪽에 있는지, 무엇을 들고 누구를 보는지까지
장면에 중요한 관계를 적는다. 행동의 주인을 서로 바꾸면 안 된다.

장소는 **지금 여기, 요즘 한국**이다.

이 동화는 오늘을 사는 아이의 이야기다. 그런데 그냥 두면 이야기가 자꾸 옛날로
흘러간다 — 마당과 대문이 있는 집, 툇마루, 장독대, 기와지붕, 초가집. 아이가
"우리 동네 같다"고 느껴야 하는 책에서 정반대 그림이 나온다.

그러니 옛날 집·시골 풍경은 **전래동화가 아닌 한 쓰지 않는다.**
쓰지 않을 것: 초가집, 기와집, 툇마루, 장독대, 대문, 사랑방, 우물, 아궁이, 한지 창호.

집 안 장면은 이런 데서 일어난다: 거실, 아이 방, 주방·식탁, 현관, 욕실, 베란다.
집을 그릴 때는 요즘 한국 아파트를 떠올린다 — 밝은 나무 마루, 크림색 벽, 큰 창과
커튼, 낮은 소파, 낮은 장난감 선반, 신발장이 있는 좁은 현관. 이건 **친구 집이나
할머니 댁도 마찬가지다.** '놀러 간다'는 장면에서 특히 옛날 집이 튀어나오는데,
그 집도 우리 집과 같은 요즘 집이다(가구 색과 배치만 다르다).
집 밖은 이런 데다: 동네 놀이터, 골목, 아파트 단지, 공원, 마트, 상가, 어린이집,
유치원, 도서관, 버스 정류장, 횡단보도.

한복도 마찬가지다. 명절이나 특별한 날이라고 이야기에 적혀 있지 않으면, 아이는
티셔츠·바지·원피스처럼 **평소 입는 옷**을 입는다.

(다만 '마당'이라는 말 자체를 금지하는 것은 아니다. 이야기가 실제로 마당 있는
집이나 시골 할머니 댁을 말하면 그건 그대로 쓴다. 기본값을 요즘 도시로 두라는 뜻이다.)

장소도 인물처럼 고정한다.

**장소는 최대 두 곳까지만 쓴다. 한 곳으로 끝낼 수 있으면 한 곳이 가장 좋다.**
그림책은 같은 자리에서 이야기가 깊어질수록 좋다 — 장소를 늘리는 건 이야기를 넓히는
게 아니라 흩뜨리는 것이다. 아이가 "여기가 아까 그 데구나" 하고 알아보는 것이 재미다.
장소를 옮기는 것은 이야기가 그것을 꼭 요구할 때뿐이다(집에서 나가야 사건이 생기는 경우 등).

각 @@IMG@@에 \`장소: 장소 이름 — 고정 특징.\`을 반드시 적는다.
고정 특징은 **그림 그리는 사람이 같은 곳을 다시 그릴 수 있을 만큼** 구체적으로 쓴다.
"물이 맑은 계곡" 같은 말로는 매번 다른 계곡이 그려진다. 아래 다섯을 이 순서로 넣는다
(이 줄이 그대로 '장소 기준 그림'의 설계도가 된다 — 빠지면 그 요소가 쪽마다 달라진다):
  ① 바닥·지면 — 자갈밭 / 밝은 나무 마루 / 잔디 / 모래 / 회색 타일
  ② 눈에 띄는 큰 것 하나 — 넓적한 바위 / 통나무 다리 / 노란 미끄럼틀 / 큰 전신 거울
  ③ 벽·둘레 — 크림색 벽과 큰 창 / 낮은 돌담 / 초록 울타리 / 나무들
  ④ 가구나 그 자리의 작은 물건 하나 — 하늘색 소파 / 나무 벤치 / 하얀 옷장 / 물가의 자갈
  ⑤ 빛·때 — 낮의 밝은 햇빛 / 저녁 노을 / 창으로 드는 오후 빛 / 스탠드 불빛
장소 이름은 실내면 실내임이 드러나게 쓴다(마트 장난감 코너, 테이네 집 거실) — '마트 입구'처럼
바깥으로 읽히는 이름은 실제로 밖일 때만 쓴다.
예: \`장소: 계곡 — 회색 자갈 바닥, 물가에 넓적한 바위 하나, 짙은 초록 나무들, 자갈 위 작은 나무 다리, 낮의 밝은 햇빛.\`
예: \`장소: 테이네 집 거실 — 밝은 나무 마루, 하늘색 소파, 크림색 벽과 큰 창, 낮은 장난감 선반, 오후 햇빛.\`

같은 장소가 다시 나오면 장소 이름과 이 고정 특징을 **앞 페이지와 한 글자도 다르지 않게
그대로 반복**한다. 말을 바꾸면 그림도 바뀐다.

물건도 장소와 똑같이 고정한다.

두 쪽 이상에 나오는 물건(아이스크림, 인형, 가방, 우산, 열쇠…)은 **매번 다른 물건으로
그려지는 것이 가장 흔한 사고다.** 1쪽에서는 콘에 담긴 딸기 아이스크림, 3쪽에서는
컵에 담긴 초코 아이스크림이 나오면 아이는 같은 물건으로 못 알아본다.

**반복되는 물건은 최대 두 개까지만 만든다.** 그리고 그 물건이 나오는 @@IMG@@마다
\`물건: 이름 — 고정 모습.\`을 적는다.

고정 모습은 **일부러 단순하게** 쓴다. 자세히 쓸수록 통일되는 게 아니라 반대다 —
꾸밀 거리가 많을수록 매번 다르게 그려진다. 아래 셋만 쓰고 더 붙이지 않는다:
  ① 색 하나 — 분홍색 / 노란색 / 빨간색
  ② 모양 하나 — 동그란 / 네모난 / 길쭉한
  ③ 담긴 것이나 크기 — 갈색 콘 위에 / 아이 손만 한
종류가 여럿인 물건(가방·통·상자·컵)은 ② 자리에 모양 대신 **종류**를 못박는다 —
'등에 메는 책가방' / '손에 드는 네모난 도시락 통'처럼. 실제로 \`노란색 네모난 가방\`이라고만
적었더니 1쪽에서는 어린이 책가방, 3쪽에서는 어른 서류가방으로 그려졌다.
예: \`물건: 아이스크림 — 분홍색 동그란 덩어리 하나, 갈색 콘 위에.\`
예: \`물건: 곰인형 — 노란 갈색, 아이 팔만 한 크기, 목에 빨간 리본 하나.\`

맛·토핑·무늬·장식을 새로 붙이지 않는다. 두 덩어리, 스프링클, 체리, 반짝임 같은 것을
한 쪽에서 붙이면 다른 쪽에서는 빠져서 결국 다른 물건이 된다.
같은 물건이 다시 나오면 이 한 줄을 **한 글자도 다르지 않게 그대로 반복**한다.

**이야기의 중심 물건은 끝까지 따라간다.** 제목에 나오거나 사건의 원인이 되는 물건
(잃어버린 모자, 찾으러 다니는 인형, 들고 다니는 도시락 같은 것)은, 그 물건이 그 쪽
그림에 **보이기만 하면** 본문에 이름이 안 나와도 \`물건:\` 줄을 적는다.

실제로 이런 사고가 났다 — 「노란 모자를 찾아라」에서 7쪽에 모자를 찾아 놓고, 8쪽
돌아오는 버스에는 아무도 모자를 안 쓰고 있었다. 8쪽 본문에 '모자'라는 낱말이 없어서
\`물건:\` 줄을 안 적었기 때문이다. 아이가 보기엔 애써 찾은 모자가 사라진 것이다.

되찾았거나 받았거나 계속 지니고 있는 물건은 **누가 그것을 쓰고 있는지 / 들고 있는지**를
장면 문장에도 한마디로 적는다(예: "하성이는 노란 모자를 쓰고 창밖을 본다").

@@TEXT@@ 안의 **모든 대사는 누가 말했는지 바로 옆 문장에 이름으로 밝힌다.**
따옴표 앞이나 뒤에 \`할머니가 말했어요\`, \`하온이가 고개를 저었어요\`처럼 **주어를 이름으로**
적는다. 그냥 "말했어요", "누군가 소리쳤어요"처럼 주어를 빼지 않는다.
이유가 둘이다. 하나는 아이가 읽을 때 누구 말인지 알아야 하기 때문이고,
또 하나는 앱이 그 이름을 보고 **할머니 대사는 느리고 낮게, 작은 동물 대사는
빠르고 높게** 읽어 주기 때문이다. 이름이 없으면 그냥 밋밋하게 읽힌다.
대사를 두 사람이 주고받으면 **각 대사마다 각각** 이름을 밝힌다.
"~라고 말했어요"는 한 쪽에 두 번을 넘기지 않는다 — 웃었어요·고개를 저었어요·
두 팔을 벌렸어요처럼 몸짓으로 누구인지 밝히는 편이 그림책답다.
본문에서 실제 이동했다고 쓰지 않은 한 장소를 집에서 한옥으로, 방에서 공원으로 임의
변경하지 않는다. 장소가 바뀌는 페이지는 @@TEXT@@에도 이동 과정이 분명히 있어야 한다.
페이지를 쓰기 전에 직전 페이지의 장소를 기억한다. 새 페이지의 장소가 다르면 @@TEXT@@에
누가 어디에서 어디로 어떻게 이동했는지 먼저 쓴다. 이동 문장이 없다면 장소 이름과 고정 특징을
직전 페이지와 똑같이 유지한다. 특히 일상 이야기에서는 재미를 위해 뜬금없는 새 장소를 만들지 않는다.

출력은 아래 마커 형식만. 앞뒤에 다른 말을 붙이지 않는다.

@@TITLE@@ 제목
@@SUMMARY@@ 한 문장 요약
@@CHARACTER@@ 이름 | 생김새와 특징
@@PAGE@@ 1
@@TEXT@@ ...
@@VOICE@@ narration=normal | dialogue=happy | intensity=0.5 | pace=normal
@@IMG@@ ...
@@PAGE@@ 2
...`;

export async function generateStory(input: {
  child: ChildProfile;
  material: StoryMaterial;
  outline: ParsedOutline;
  occasion?: string;
  mood?: string;
  /** 넉넉하게(길게) — 쪽수가 적어도 각 쪽 분량을 늘려 이야기를 더 풍부하게. */
  longer?: boolean;
  /** 제작 단계에서 한 번 고르고 책에 고정하는 낭독 느낌. */
  narrationStyle?: NarrationStyle;
}): Promise<ParsedStory> {
  // 쪽수는 줄거리 장면 수를 그대로 따른다 — 장면 1개 = 쪽 1개.
  const pageCount = input.outline.scenes.length;

  const outlineText = input.outline.scenes
    .map((s) => `${s.sceneNo}장면: ${s.text}`)
    .join("\n");
  const narrationStyle = input.narrationStyle ?? "natural";
  const narrationStyleGuide = {
    cozy:
      "선택한 낭독 느낌은 '포근하게'다. narration=normal, intensity=0.35, pace=slow를 기본으로 하고 대사는 대부분 normal로 지정한다. 슬픈 대사만 sad를 약하게 허용한다.",
    natural:
      "선택한 낭독 느낌은 '자연스럽게'다. narration=normal, intensity=0.5, pace=normal을 기본으로 하고 감정이 분명한 대사에만 happy|sad|angry를 지정한다.",
    lively:
      "선택한 낭독 느낌은 '조금 신나게'다. narration=normal, intensity=0.6, pace=lively를 기본으로 하되 슬프거나 조용한 장면은 pace=normal로 낮춘다. 높은 음정이나 과장은 금지한다.",
  }[narrationStyle];

  // 이름 가드 — 줄거리와 같은 방식. 본문에서 이름이 틀리면 한 번 다시 짓는다.
  let story: ParsedStory | null = null;
  let lastIssues: string[] = [];
  for (let attempt = 1; attempt <= 2; attempt++) {
    const message = await client.messages.create({
      model: MODEL,
      max_tokens: 8000,
      system: STORY_SYSTEM,
      thinking: { type: "adaptive" },
      output_config: { effort: "medium" },
      messages: [
        {
          role: "user",
          content: [
            `아이: ${describeChild(input.child)}`,
            `장면 수: ${pageCount}장면 (이 개수만큼, 장면 하나당 한 쪽씩 낸다)`,
            `쪽당 분량: ${lengthGuide(input.child.age, input.longer)}`,
            "처음 입력한 이야기 재료(사실·인물·장소)는 줄거리보다 우선하며, 빠뜨리거나 다른 내용으로 바꾸지 않는다.",
            ...materialLines(input.material),
            "각 페이지에는 @@VOICE@@를 정확히 한 번 쓴다. 부모가 잠자리에서 책을 읽어주는 듯 낮고 편안한 낭독을 기준으로 한다. narration은 항상 normal이다. dialogue는 기본 normal이며 감정이 분명한 짧은 대사에만 happy|sad|angry를 쓴다(toneup은 사용하지 않는다). intensity는 0.3~0.65이고 기본 0.5다. pace는 기본 normal, 아주 차분한 장면은 slow, lively는 꼭 필요한 장면에만 쓴다. 신나는 감정은 높은 음정이나 빠른 말투가 아니라 자연스러운 리듬과 미소로 표현한다.",
            narrationStyleGuide,
            ...(input.occasion
              ? [`특별한 날: ${input.occasion} — 축하가 이야기에 자연스럽게 스며들게.`]
              : []),
            ...(input.mood ? [`분위기: ${input.mood}`] : []),
            ...(attempt > 1
              ? [
                  `직전 결과의 품질 검사 실패 항목: ${lastIssues.join(" / ")}. 이 항목을 모두 바로잡아 전체를 다시 출력한다.`,
                  `경고: 직전 생성에서 주인공 이름 표기가 틀렸다. 이름은 "${input.child.name}"이다 — 비슷한 다른 이름 절대 금지. (조사는 자연스럽게: ${josaGuide(input.child.name)})`,
                ]
              : []),
            "",
            `제목: ${input.outline.title}`,
            "장면별 줄거리:",
            outlineText,
          ].join("\n"),
        },
      ],
    });

    story = repairStoryContinuity(parseStory(textOf(message)));

    lastIssues = validateStoryQuality(story, {
      childName: input.child.name,
      age: input.child.age,
      expectedPages: pageCount,
      requiredTerms: [
        input.material.whoName,
        ...input.material.friends.map((friend) => friend.name),
        input.material.place.length <= 20 ? input.material.place : "",
      ].filter(Boolean),
    });
    if (lastIssues.length === 0) break;
    if (attempt === 2) {
      const blockingIssues = lastIssues.filter(isBlockingStoryQualityIssue);
      if (blockingIssues.length > 0) throw new StoryQualityError(blockingIssues);
      console.warn(`[story] 자동 보정 후 진행하는 품질 권고: ${lastIssues.join(" / ")}`);
    }
  }

  // 아이가 보게 될 최종 본문이라 여기서 한 번 더 조사를 맞춘다.
  // 등장인물 이름은 손대지 않는다 — 모델이 "동생"처럼 보통명사를 인물 이름으로
  // 넣는 일이 있어, 확실히 사람 이름인 주인공만 고친다.
  const fix = (t: string) => fixNameJosa(input.child.name, nfc(t));
  const lockDirection = (page: ParsedStory["pages"][number]) => {
    const dialogue = page.voiceDirection.dialogue === "toneup" ? "normal" : page.voiceDirection.dialogue;
    if (narrationStyle === "cozy") {
      return {
        ...page,
        voiceDirection: {
          narration: "normal" as const,
          dialogue: dialogue === "sad" ? "sad" as const : "normal" as const,
          intensity: 0.35,
          pace: "slow" as const,
        },
      };
    }
    if (narrationStyle === "lively") {
      return {
        ...page,
        voiceDirection: {
          narration: "normal" as const,
          dialogue,
          intensity: 0.6,
          pace: page.voiceDirection.pace === "slow" ? "normal" as const : "lively" as const,
        },
      };
    }
    return {
      ...page,
      voiceDirection: {
        narration: "normal" as const,
        dialogue,
        intensity: 0.5,
        pace: "normal" as const,
      },
    };
  };
  return {
    ...story!,
    title: fix(story!.title),
    summary: nfc(story!.summary),
    // 등장인물 묘사도 맞춘다 — 이 글이 그대로 그림 프롬프트로 간다.
    characters: story!.characters.map((c) => ({
      name: nfc(c.name),
      description: nfc(c.description),
    })),
    pages: story!.pages.map((p) => lockDirection({ ...p, text: fix(p.text), imagePrompt: nfc(p.imagePrompt) })),
  };
}

function textOf(message: Anthropic.Message): string {
  return message.content
    .filter((b): b is Anthropic.TextBlock => b.type === "text")
    .map((b) => b.text)
    .join("\n");
}
