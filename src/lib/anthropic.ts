  subject: string; // 상상: 소재(공룡 등)
  who: string; // 누구랑 (공통) — 칩 라벨(친구랑·동생이랑 등)
  whoName: string; // 동행의 실제 이름(선택). 있으면 그 이름을 그대로 쓴다.
