/**
 * 새 소식(공지) — 부모에게 "이번에 뭐가 바뀌었는지" 알리는 글.
 *
 * 여기 한 곳만 고치면 앱 전체 공지가 바뀐다. 다음에 알릴 것이 생기면
 * LATEST_UPDATE를 통째로 새로 쓰고 **id를 반드시 바꾼다** — id가 바뀌어야
 * 이미 닫은 사람에게도 새 공지가 다시 뜬다. 안 바꾸면 아무도 못 본다.
 *
 * 왜 화면에 박아 두는가: 회원이 넷인 베타다. 공지 하나 띄우려고 표를 만들고
 * 관리 화면을 붙이면 그게 더 큰 일이 된다. 실수로 지워질 일도 없다.
 * (같은 이유로 의견 게시판의 관리자 공지도 화면에 박혀 있다.)
 *
 * 글을 쓸 때 — 읽는 사람은 개발자가 아니라 아이 부모다.
 *   · 무엇이 좋아졌는지를 부모의 말로. '토큰 분리', 'QA' 같은 말은 쓰지 않는다.
 *   · 부모가 해야 할 일이 있으면 그것만 또렷하게.
 *   · 다섯 줄을 넘기지 않는다. 길면 안 읽는다.
 */

export type UpdateItem = {
  /** 공개 아이콘(이모지) — 한 눈에 어떤 갈래인지. */
  icon: string;
  title: string;
  body: string;
};

export type UpdateNote = {
  /** 이 공지의 이름표. 바꾸면 이미 닫은 사람에게도 다시 뜬다. */
  id: string;
  /** 화면에 그대로 보여줄 날짜. */
  date: string;
  headline: string;
  items: UpdateItem[];
  /** 맨 아래 한 줄 — 부탁이나 안내. 없으면 안 보인다. */
  footer?: string;
};

